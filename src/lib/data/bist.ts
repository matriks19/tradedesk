const YAHOO_CHART = "https://query1.finance.yahoo.com/v8/finance/chart";

const TF_TO_YAHOO: Record<
  Timeframe,
  { interval: string; range: string }
> = {
  "1m": { interval: "1m", range: "1d" },
  "3m": { interval: "5m", range: "5d" },
  "5m": { interval: "5m", range: "5d" },
  "15m": { interval: "15m", range: "5d" },
  "30m": { interval: "30m", range: "1mo" },
  "1h": { interval: "60m", range: "1mo" },
  "2h": { interval: "60m", range: "3mo" },
  "4h": { interval: "60m", range: "3mo" },
  "6h": { interval: "1d", range: "6mo" },
  "12h": { interval: "1d", range: "1y" },
  "1d": { interval: "1d", range: "1y" },
  "1w": { interval: "1wk", range: "5y" },
};

function uniqBist(): { symbol: string; name: string }[] {
  const map = new Map<string, string>();
  for (const t of [...BIST_TICKERS, ...BIST_EXTRA]) {
    if (!map.has(t.symbol)) map.set(t.symbol, t.name);
  }
  return [...map.entries()]
    .map(([symbol, name]) => ({ symbol, name }))
    .sort((a, b) => a.symbol.localeCompare(b.symbol));
}

export class BistProvider {
  static listSymbols(): SymbolInfo[] {
    return uniqBist().map((t) => ({
      symbol: t.symbol,
      exchange: "bist",
      name: t.name,
      base: t.symbol,
      quote: "TRY",
    }));
  }

  static yahooSymbol(symbol: string): string {
    const s = symbol.toUpperCase().replace(/\.IS$/i, "");
    return `${s}.IS`;
  }

  static async getKlines(
    symbol: string,
    timeframe: Timeframe,
    _limit = 500
  ): Promise<{ candles: Candle[]; delayed: true; note: string }> {
    const { interval, range } = TF_TO_YAHOO[timeframe] ?? TF_TO_YAHOO["1d"];
    const ysym = this.yahooSymbol(symbol);
    const url = `${YAHOO_CHART}/${encodeURIComponent(
      ysym
    )}?interval=${interval}&range=${range}`;
    const res = await fetch(url, {
      cache: "no-store",
      headers: { "User-Agent": "TradeDesk/1.0" },
    });
    if (!res.ok) {
      throw new Error(
        `BIST/Yahoo klines ${res.status} — gecikmeli/public kaynak kullanılamadı`
      );
    }
    const json = await res.json();
    const result = json?.chart?.result?.[0];
    if (!result) throw new Error("BIST: boş yanıt");
    const ts: number[] = result.timestamp ?? [];
    const q = result.indicators?.quote?.[0] ?? {};
    const candles: Candle[] = [];
    for (let i = 0; i < ts.length; i++) {
      const o = q.open?.[i];
      const h = q.high?.[i];
      const l = q.low?.[i];
      const c = q.close?.[i];
      const v = q.volume?.[i];
      if ([o, h, l, c].some((x) => x == null || Number.isNaN(Number(x)))) continue;
      candles.push({
        time: ts[i],
        open: Number(o),
        high: Number(h),
        low: Number(l),
        close: Number(c),
        volume: Number(v ?? 0),
      });
    }
    return {
      candles,
      delayed: true,
      note: "BIST verisi Yahoo Finance public endpoint üzerinden gecikmeli/best-effort",
    };
  }

  static async getQuotes(symbols: string[]): Promise<TickerQuote[]> {
    const out: TickerQuote[] = [];
    // Batch via Yahoo quote API (best-effort)
    const chunk = symbols.slice(0, 50);
    const ysyms = chunk.map((s) => this.yahooSymbol(s)).join(",");
    try {
      const url = `https://query1.finance.yahoo.com/v7/finance/quote?symbols=${encodeURIComponent(ysyms)}`;
      const res = await fetch(url, {
        cache: "no-store",
        headers: { "User-Agent": "TradeDesk/1.0" },
      });
      if (!res.ok) return out;
      const json = await res.json();
      const results = json?.quoteResponse?.result ?? [];
      for (const r of results) {
        const sym = String(r.symbol || "").replace(/\.IS$/i, "");
        out.push({
          symbol: sym,
          exchange: "bist",
          last: Number(r.regularMarketPrice ?? 0),
          changePct: Number(r.regularMarketChangePercent ?? 0),
          high24h: Number(r.regularMarketDayHigh ?? 0),
          low24h: Number(r.regularMarketDayLow ?? 0),
          volume: Number(r.regularMarketVolume ?? 0),
          delayed: true,
        });
      }
    } catch {
      // leave empty — UI shows delayed banner
    }
    return out;
  }
}
